#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
/**
 * 构建浏览器半边：src/client/index.tsx → lib/client.js
 *
 * DSH 的 client 模块加载协议：
 *   window.__ModuleLoader__.load({ id, factory })
 *   factory(require) 返回 { name, inject, apply }
 * React / jsx-runtime 交给宿主（external），其余打包进 IIFE。
 */
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await import('node:fs/promises').then(fs => fs.readFile(resolve(root, 'package.json'), 'utf8')))

const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.tsx'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  logLevel: 'silent',
})

const code = result.outputFiles[0].text
const wrapped = `/* ${pkg.name} client - generated by scripts/build-client.mjs, do not edit */
;(() => {
  window.__ModuleLoader__.load({
    id: ${JSON.stringify(pkg.name)},
    factory: (require) => {
      const module = { exports: {} };
      const exports = module.exports;
${code}
      return module.exports;
    },
  });
})();
`

mkdirSync(resolve(root, 'lib'), { recursive: true })
writeFileSync(resolve(root, 'lib/client.js'), wrapped)
console.log(`client bundle → lib/client.js (${wrapped.length} bytes)`)
